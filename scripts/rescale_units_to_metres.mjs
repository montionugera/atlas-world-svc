#!/usr/bin/env node
// F-185 Phase 2: one-shot content rescale, old server units (0.1 m) -> metres (1 unit = 1 m).
// Contract: docs/unit-contract.md. Idempotent: every file it changes gets the marker
// "unitContract": "metres-v1" and a file that already has it is skipped.
//
// What is divided by 10 (these were SERVER units: coord_scale 0.1, centre = width/2):
//   content/maps/<map>.json  width, height, playerSpawn{x,y}, spawnAreas[x,y,width,height],
//                            staticObstacles[min_x,min_y,max_x,max_y]
//   content/maps/_manifest.runtime.json  starterSpawns[*].{x,y},
//                            portalRoutingTable[*].triggerBoxMeters{x,y,width,height},
//                            arrivalPointMeters{x,y}
//   content/studio/nodes/**.json  terrain_tile.dimensions_meters{width,height},
//                            starter_arrival_binding.spawn_point_meters{x,y} (z stays),
//                            portals.*.trigger_box_meters{x,y,width,height},
//                            portals.*.arrival_point_meters{x,y}
// NOT divided (already metres, relative to the map centre, read by the clients):
//   routes, groundZones, heightTerraces, structures, props, chunkSizeWorld, palettes'
//   minSpacingMeters, safeZoneRadiusMeters (true metres: 40 m), content/towns/*.json (own
//   design frame, shared with atelier tools; the server converts it at load).
// The 44 maps made by scripts/compile_world_maps.py are regenerated by it (same numbers);
// this script is what moves the hand-authored files and gives every file the marker.
// Output keeps each file's indent and Python json.dumps formatting (4000.0 floats, \uXXXX escapes) so diffs stay
// minimal and compile_world_maps.py --check can compare bytes.
// Usage: node scripts/rescale_units_to_metres.mjs [--check]   (--check: exit 1 if work remains)
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const MARKER_KEY = "unitContract";
export const MARKER_VAL = "metres-v1";
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// A number that was written with a "." or exponent in the source (Python float).
class Flt {
  constructor(v) {
    this.v = v;
  }
}
const parse = (text) =>
  JSON.parse(text, (_k, v, ctx) => (typeof v === "number" && /[.eE]/.test(ctx?.source ?? "") ? new Flt(v) : v));

const pyFloat = (v) => (Object.is(v, -0) ? "-0.0" : Number.isInteger(v) ? v.toFixed(1) : String(v));
const esc = (s) =>
  JSON.stringify(s).replace(/[\u007f-￿]/g, (c) => "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0"));
function dump(o, ind = "", unit = "  ") {
  const inner = ind + unit;
  if (o instanceof Flt) return pyFloat(o.v);
  if (Array.isArray(o)) {
    if (!o.length) return "[]";
    return "[\n" + o.map((x) => inner + dump(x, inner, unit)).join(",\n") + "\n" + ind + "]";
  }
  if (o && typeof o === "object") {
    const ks = Object.keys(o);
    if (!ks.length) return "{}";
    return "{\n" + ks.map((k) => `${inner}${esc(k)}: ${dump(o[k], inner, unit)}`).join(",\n") + "\n" + ind + "}";
  }
  return typeof o === "string" ? esc(o) : JSON.stringify(o);
}

// 2 decimals: old values carried 1 decimal in 0.1 m units, so /10 is exact at 2 decimals.
// Integer sources stay integers when the result is whole, floats stay floats.
const d = (n) => {
  const v = n instanceof Flt ? n.v : n;
  const r = Math.round((v / 10) * 100) / 100;
  return n instanceof Flt || !Number.isInteger(r) ? new Flt(r) : r;
};
const isNum = (v) => typeof v === "number" || v instanceof Flt;
const scale = (obj, keys) => {
  if (!obj || typeof obj !== "object") return;
  for (const k of keys) if (isNum(obj[k])) obj[k] = d(obj[k]);
};
const each = (arr, f) => Array.isArray(arr) && arr.forEach(f);

// Marker goes right after "version"/"schemaVersion" (else first) so key order is stable.
function withMarker(doc) {
  const out = {};
  let placed = false;
  for (const [k, v] of Object.entries(doc)) {
    out[k] = v;
    if (!placed && (k === "version" || k === "schemaVersion")) {
      out[MARKER_KEY] = MARKER_VAL;
      placed = true;
    }
  }
  return placed ? out : { [MARKER_KEY]: MARKER_VAL, ...out };
}

export function rescaleMap(doc) {
  scale(doc, ["width", "height"]);
  scale(doc.playerSpawn, ["x", "y"]);
  each(doc.spawnAreas, (s) => scale(s, ["x", "y", "width", "height"]));
  each(doc.staticObstacles, (o) => scale(o, ["min_x", "min_y", "max_x", "max_y"]));
}

export function rescaleManifest(doc) {
  for (const s of Object.values(doc.starterSpawns ?? {})) scale(s, ["x", "y"]);
  for (const p of Object.values(doc.portalRoutingTable ?? {})) {
    scale(p.triggerBoxMeters, ["x", "y", "width", "height"]);
    scale(p.arrivalPointMeters, ["x", "y"]);
  }
}

export function rescaleStudioNode(doc) {
  scale(doc.terrain_tile?.dimensions_meters, ["width", "height"]);
  scale(doc.starter_arrival_binding?.spawn_point_meters, ["x", "y"]);
  for (const p of Object.values(doc.portals ?? {})) {
    if (!p) continue;
    scale(p.trigger_box_meters, ["x", "y", "width", "height"]);
    scale(p.arrival_point_meters, ["x", "y"]);
  }
}

function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (n.endsWith(".json")) out.push(p);
  }
  return out;
}

const touchesStudio = (doc) =>
  doc.terrain_tile?.dimensions_meters ||
  doc.starter_arrival_binding?.spawn_point_meters ||
  Object.values(doc.portals ?? {}).some((p) => p && (p.trigger_box_meters || p.arrival_point_meters));

/** Rescale every content file under `root`. Returns counts; with check, writes nothing. */
export function run({ check = false, root = ROOT } = {}) {
  const maps = join(root, "content/maps");
  const targets = [
    ...readdirSync(maps)
      .filter((n) => n.endsWith(".json"))
      .map((n) => [join(maps, n), n === "_manifest.runtime.json" ? rescaleManifest : rescaleMap]),
    ...walk(join(root, "content/studio/nodes")).map((p) => [p, rescaleStudioNode]),
  ];
  let changed = 0;
  let skipped = 0;
  for (const [path, fn] of targets) {
    const doc = parse(readFileSync(path, "utf8"));
    if (doc[MARKER_KEY] === MARKER_VAL) {
      skipped++;
      continue;
    }
    if (fn === rescaleStudioNode && !touchesStudio(doc)) continue;
    fn(doc);
    changed++;
    if (!check) {
      const text = readFileSync(path, "utf8");
      const unit = text.match(/^\{\n( +)\S/)?.[1] ?? "  "; // keep the file's own indent (maro-bell uses 1 space)
      writeFileSync(path, dump(withMarker(doc), "", unit) + "\n");
    };
  }
  return { changed, skipped };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const { changed, skipped } = run({ check });
  console.log(`rescale_units_to_metres: ${check ? "would change" : "changed"} ${changed}, already metres-v1 ${skipped}`);
  if (check && changed) process.exit(1);
}
